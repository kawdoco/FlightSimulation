CREATE TABLE aircraft (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT,
 registration_number VARCHAR(255) NOT NULL UNIQUE, model VARCHAR(255) NOT NULL,
 manufacturer VARCHAR(255) NOT NULL, status VARCHAR(255) NOT NULL,
 fuel_capacity DOUBLE PRECISION, max_speed DOUBLE PRECISION, max_altitude DOUBLE PRECISION
);
CREATE TABLE flights (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT,
 flight_number VARCHAR(255) NOT NULL UNIQUE, departure VARCHAR(255) NOT NULL,
 destination VARCHAR(255) NOT NULL, scheduled_time TIMESTAMP(6), start_time TIMESTAMP(6),
 end_time TIMESTAMP(6), status VARCHAR(255) NOT NULL, aircraft_id BIGINT NOT NULL REFERENCES aircraft(id)
);
CREATE TABLE telemetry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 altitude DOUBLE PRECISION, speed DOUBLE PRECISION, pitch DOUBLE PRECISION, roll DOUBLE PRECISION,
 heading DOUBLE PRECISION, throttle DOUBLE PRECISION, fuel DOUBLE PRECISION,
 recorded_at TIMESTAMP(6), flight_id BIGINT NOT NULL REFERENCES flights(id)
);
CREATE INDEX idx_telemetry_flight_recorded ON telemetry(flight_id,recorded_at);
CREATE TABLE alerts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT,
 aircraft_id BIGINT NOT NULL, flight_id BIGINT, type VARCHAR(255) NOT NULL,
 message VARCHAR(1000) NOT NULL, severity VARCHAR(255) NOT NULL, status VARCHAR(255) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL, resolved_at TIMESTAMP(6)
);
CREATE TABLE iot_devices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 device_name VARCHAR(255) NOT NULL, device_type VARCHAR(255), device_identifier VARCHAR(255) UNIQUE,
 status VARCHAR(255), ip_address VARCHAR(255), last_seen TIMESTAMP(6)
);
CREATE TABLE maintenance_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT,
 aircraft_id BIGINT NOT NULL, description VARCHAR(1000) NOT NULL, status VARCHAR(255) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL, completed_at TIMESTAMP(6)
);
CREATE TABLE application_users (
 username VARCHAR(100) PRIMARY KEY, password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(255) NOT NULL, enabled BOOLEAN DEFAULT TRUE NOT NULL, version BIGINT
);
CREATE TABLE audit_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor VARCHAR(255) NOT NULL, action VARCHAR(255) NOT NULL, target VARCHAR(255) NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_audit_created ON audit_records(created_at);
